use snellar_core::model::{Track, Upload};

use super::{Cand, Taste};
use crate::lyrics::norm;

pub(super) const LONGEST: f64 = 720.0;
pub(super) const ONLY_A_VERSION: f64 = 0.7;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum Version {
    Live,
    Cover,
    Remix,
    Speed,
    Other,
}

const WORDS: [(&str, Version); 22] = [
    ("live", Version::Live),
    ("en vivo", Version::Live),
    ("ao vivo", Version::Live),
    ("cover", Version::Cover),
    ("tribute", Version::Cover),
    ("karaoke", Version::Cover),
    ("remix", Version::Remix),
    ("rmx", Version::Remix),
    ("sped up", Version::Speed),
    ("speed up", Version::Speed),
    ("slowed", Version::Speed),
    ("nightcore", Version::Speed),
    ("reverb", Version::Speed),
    ("8d", Version::Speed),
    ("daycore", Version::Speed),
    ("bass boosted", Version::Speed),
    ("instrumental", Version::Other),
    ("acapella", Version::Other),
    ("lyric", Version::Other),
    ("lyrics", Version::Other),
    ("1 hour", Version::Other),
    ("10 hours", Version::Other),
];

const SEPARATORS: [&str; 6] = [" - ", " – ", " — ", " | ", " // ", " ~ "];
const SPEED_MARKS: [&str; 7] = ["slowed", "sped up", "speed up", "nightcore", "daycore", "8d", "bass boosted"];

/// Phrases by which a title, a channel or an artist name says it was made by AI. Whole words only, and never "AI" alone
/// (a singer, a word in many languages) or "Suno" alone (a Hindi word in many song titles).
const MADE_BY_AI: [&str; 11] = [
    "ai cover",
    "ai covers",
    "ai version",
    "ai generated",
    "generated by ai",
    "made with ai",
    "made by ai",
    "suno ai",
    "udio ai",
    "made with suno",
    "made with udio",
];

/// An artist this many releases on Deezer with fewer fans than `FARM_FANS` is a release farm, not a person.
pub(super) const FARM_RELEASES: u64 = 200;
pub(super) const FARM_FANS: u64 = 1000;

fn says(text: &str, phrase: &str) -> bool {
    let normal = norm(text);
    let words: Vec<&str> = normal.split(' ').collect();
    let wanted: Vec<&str> = phrase.split(' ').collect();
    words.windows(wanted.len()).any(|w| w == wanted.as_slice())
}

fn kinds(title: &str) -> Vec<Version> {
    let mut found: Vec<Version> = Vec::new();
    for (phrase, kind) in WORDS {
        if !found.contains(&kind) && says(title, phrase) {
            found.push(kind);
        }
    }
    found
}

pub(super) fn made_by_ai(text: &str) -> bool {
    MADE_BY_AI.iter().any(|phrase| says(text, phrase))
}

pub(super) fn farm(releases: u64, fans: u64) -> bool {
    releases >= FARM_RELEASES && fans < FARM_FANS
}

/// The version a track is. On a YouTube Music song (an album track) only the marks around the title count, in brackets or
/// after " - ": a word of the name itself ("Live Forever", "Cover Me", "Remix to Ignition") is the song, not a version.
/// Videos and uploads are read whole, since fan uploads name a version without brackets ("song slowed reverb").
pub(super) fn version_of(t: &Track) -> Option<Version> {
    kinds_of(t).first().copied()
}

pub(super) fn kinds_of(t: &Track) -> Vec<Version> {
    if t.upload != Upload::Song {
        return kinds(&t.title);
    }
    kinds_in(&t.title, t.artists.first().map_or("", |a| a.name.as_str()))
}

pub(super) fn version_in(title: &str, artist: &str) -> Option<Version> {
    kinds_in(title, artist).first().copied()
}

fn kinds_in(title: &str, artist: &str) -> Vec<Version> {
    let rest = title.replacen(&bare_title(title, artist), " ", 1);
    let rest = match rest.split_once(" - ") {
        Some((head, tail)) if !norm(artist).is_empty() && norm(head) == norm(artist) => tail.to_string(),
        _ => rest,
    };
    kinds(&rest)
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub(super) struct Versions {
    pub live: bool,
    pub cover: bool,
    pub remix: bool,
    pub speed: bool,
}

impl Versions {
    pub fn allows_version(&self, version: Option<Version>) -> bool {
        match version {
            None => true,
            Some(Version::Live) => self.live,
            Some(Version::Cover) => self.cover,
            Some(Version::Remix) => self.remix,
            Some(Version::Speed) => self.speed,
            Some(Version::Other) => false,
        }
    }

    pub fn bars_version(&self, version: Option<Version>) -> bool {
        matches!(version, Some(Version::Live | Version::Cover | Version::Remix | Version::Speed)) && !self.allows_version(version)
    }

    pub fn bars(&self, t: &Track) -> bool {
        kinds_of(t).into_iter().any(|v| self.bars_version(Some(v)))
    }

    pub fn bars_title(&self, title: &str, artist: &str) -> bool {
        kinds_in(title, artist).into_iter().any(|v| self.bars_version(Some(v)))
    }

    pub fn allows_all(&self, t: &Track) -> bool {
        kinds_of(t).into_iter().all(|v| self.allows_version(Some(v)))
    }
}

pub(super) fn grade(t: &Track) -> i32 {
    let kind = match t.upload {
        Upload::Song => 4,
        Upload::Official => 3,
        Upload::Video | Upload::Unknown => 2,
        Upload::User => 0,
        Upload::Podcast => -100,
    };
    kind + if version_of(t).is_some() { 0 } else { 10 }
}

pub(super) fn better(a: Option<Track>, b: Option<Track>) -> Option<Track> {
    match (a, b) {
        (Some(a), Some(b)) => Some(if grade(&b) > grade(&a) { b } else { a }),
        (a, b) => a.or(b),
    }
}

pub(super) fn bare_title(title: &str, artist: &str) -> String {
    let mut bare = String::new();
    let mut depth = 0;
    for c in title.chars() {
        match c {
            '(' | '[' | '{' | '【' => depth += 1,
            ')' | ']' | '}' | '】' if depth > 0 => depth -= 1,
            _ if depth == 0 => bare.push(c),
            _ => {}
        }
    }
    let unified = SEPARATORS.iter().fold(bare, |t, s| t.replace(s, " - "));
    let parts: Vec<&str> = unified.split(" - ").map(str::trim).filter(|p| !p.is_empty()).collect();
    let head = match parts.as_slice() {
        [first, second, ..] if !norm(artist).is_empty() && norm(first) == norm(artist) => second,
        [first, ..] => first,
        [] => "",
    };
    let head = before_a_speed_mark(head);
    if head.is_empty() { title.trim().to_string() } else { head.to_string() }
}

fn before_a_speed_mark(text: &str) -> &str {
    let mut starts = Vec::new();
    let mut after_space = true;
    for (i, c) in text.char_indices() {
        if after_space && !c.is_whitespace() {
            starts.push(i);
        }
        after_space = c.is_whitespace();
    }
    for &at in starts.iter().skip(1) {
        let rest = norm(&text[at..]);
        if SPEED_MARKS.iter().any(|m| rest == *m || rest.starts_with(&format!("{m} "))) {
            return text[..at].trim_end_matches(|c: char| c.is_whitespace() || "+&-–—,|/~:".contains(c));
        }
    }
    text
}

pub(super) fn blocked_track(t: &Track, taste: &Taste) -> bool {
    let named = |name: &str| taste.disliked_artists.contains(&norm(name));
    t.artists.iter().any(|a| named(&a.name)) || t.uploader.as_ref().is_some_and(|u| named(&u.name)) || taste.unplayable.contains(&t.id)
}

pub(super) fn blocked(c: &Cand, taste: &Taste) -> bool {
    taste.disliked_artists.contains(&norm(&c.artist))
        || c.track.as_ref().is_some_and(|t| blocked_track(t, taste))
        || c.fallback.as_ref().is_some_and(|t| blocked_track(t, taste))
}

/// Whether the AI and spam filter leaves a track out: a track by a release farm or one that says it was made by AI.
/// Never a track by an artist the person knows (liked, played, listed or followed); off when the switch is off.
pub(super) fn spam_track(t: &Track, taste: &Taste) -> bool {
    if !taste.hide_spam || t.artists.iter().any(|a| taste.known_artists.contains(&norm(&a.name))) {
        return false;
    }
    t.artists.iter().any(|a| spam_artist(&a.name, taste))
        || t.uploader.as_ref().is_some_and(|u| spam_artist(&u.name, taste))
        || made_by_ai(&t.title)
}

pub(super) fn spam_artist(name: &str, taste: &Taste) -> bool {
    let k = norm(name);
    taste.hide_spam && !taste.known_artists.contains(&k) && (taste.farms.contains(&k) || made_by_ai(name))
}

pub(super) fn spam(c: &Cand, taste: &Taste) -> bool {
    if !taste.hide_spam || taste.known_artists.contains(&norm(&c.artist)) {
        return false;
    }
    spam_artist(&c.artist, taste)
        || made_by_ai(&c.title)
        || c.track.as_ref().is_some_and(|t| spam_track(t, taste))
        || c.fallback.as_ref().is_some_and(|t| spam_track(t, taste))
}

pub(super) fn unwanted(t: &Track) -> bool {
    t.upload == Upload::Podcast || t.duration > LONGEST
}

pub(super) fn wants_the_original(t: &Track, versions: Versions) -> bool {
    t.upload == Upload::User || !versions.allows_all(t)
}
